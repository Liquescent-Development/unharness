    #[test]
    fn frontmatter_closes_on_its_own_line() {
        let (front, body) = split_frontmatter("---\n---\nBody\n").unwrap();
        assert!(front.is_empty());
        assert_eq!(body, "Body\n");
        let (front, body) = split_frontmatter("---\r\ndescription: D\r\n---\r\nBody\r\n").unwrap();
        assert_eq!(front.get("description").and_then(|v| v.as_str()), Some("D"));
        assert_eq!(body, "Body\r\n");
        // A longer rule inside a block scalar does not close it.
        let (front, body) = split_frontmatter("---\ndescription: |\n  a\n  ----\n---\nB").unwrap();
        assert_eq!(
            front.get("description").and_then(|v| v.as_str()),
            Some("a\n----\n")
        );
        assert_eq!(body, "B");
        assert!(split_frontmatter("---\nname: x\n").is_err());
        let (front, body) = split_frontmatter("No frontmatter").unwrap();
        assert!(front.is_empty() && body == "No frontmatter");
    }
