    #[test]
    fn an_up_to_date_role_made_read_only_is_left_alone() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        write(root, ".agents/agents/reviewer.md", AGENT);
        sync_projections(root).unwrap();
        let role = root.join(".codex/agents/reviewer.toml");
        fs::set_permissions(&role, fs::Permissions::from_mode(0o444)).unwrap();
        // Root opens it for writing anyway.
        let writable = fs::OpenOptions::new().write(true).open(&role).is_ok();

        let r = sync_projections(root).unwrap();
        if !writable {
            assert!(r.warnings.is_empty(), "{:?}", r.warnings);
        }
        assert!(r.written.is_empty(), "{:?}", r.written);
        // One that is not up to date is replaced, and stays read-only.
        write(
            root,
            ".agents/agents/reviewer.md",
            &AGENT.replace("Reviews code", "Reviews diffs"),
        );
        let r = sync_projections(root).unwrap();
        assert!(r.warnings.is_empty(), "{:?}", r.warnings);
        assert_eq!(r.written, [PathBuf::from(".codex/agents/reviewer.toml")]);
        assert!(fs::read_to_string(&role).unwrap().contains("Reviews diffs"));
        let mode = fs::metadata(&role).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o444);
        // Nothing is left beside it.
        assert_eq!(fs::read_dir(root.join(".codex/agents")).unwrap().count(), 1);
    }

